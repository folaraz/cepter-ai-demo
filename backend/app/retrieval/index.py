"""`lens index`: one embedded chunk per paragraph, for Ask's retrieval (SPEC C13).

A chunk's content is `chunk_text` from backend/ask.yaml, e.g. "Lease, Bracken Farm —
3. Term: The Landlord lets the Property...". Chunks whose content and embedding model
are unchanged are left alone, so re-indexing is cheap and idempotent. The full-text
column `tsv` is generated by Postgres from the content and never written here.
"""

from dataclasses import dataclass

from psycopg import Connection

from app.db.repositories import chunks as chunks_repo
from app.db.repositories import documents
from app.domain.chunks import Chunk
from app.domain.documents import Document, Paragraph
from app.retrieval.config import retrieval_config
from app.retrieval.embed import embed_passages


@dataclass(frozen=True)
class IndexResult:
    written: int
    unchanged: int


def chunk_content(document: Document, paragraph: Paragraph) -> str:
    return retrieval_config().chunk_text.format(
        document_title=document.title, heading=paragraph.heading or "", text=paragraph.text
    )


def build_index(conn: Connection) -> IndexResult:
    config = retrieval_config()
    docs = {d.id: d for d in documents.list_documents(conn)}
    wanted = {
        p.id: (p, chunk_content(docs[p.document_id], p)) for p in documents.list_paragraphs(conn)
    }
    stored = {c.paragraph_id: c for c in chunks_repo.list_chunks(conn)}
    stale = [
        (p, content)
        for pid, (p, content) in wanted.items()
        if pid not in stored
        or stored[pid].content != content
        or stored[pid].embedding_model != config.embedding_model
    ]
    if stale:
        vectors = embed_passages(content for _, content in stale)
        chunks_repo.upsert_chunks(
            conn,
            [
                Chunk(
                    paragraph_id=p.id,
                    document_id=p.document_id,
                    content=content,
                    embedding=vector,
                    embedding_model=config.embedding_model,
                )
                for (p, content), vector in zip(stale, vectors, strict=True)
            ],
        )
    return IndexResult(written=len(stale), unchanged=len(wanted) - len(stale))
